"""
   ucp_data.py: data for ucp/load dispatch

   Based on:
   [1] Wood A, Wollenberg B. Power Generation, Operation, and Control. New York, NY: John Wiley & Sons; 1984.
   [2] Kazarlis SA, Bakirtzis AG, Petridis V. A genetic algorithm solution to the unit commitment problem. IEEE Transactions on Power Systems 1996;11:83-92.
   [3] dos Santos Coelho L, Mariani VC. An efficient cultural self-organizing migrating strategy for economic dispatch optimization with valve-point effect. Energy Conversion and Management 2010;51(12):2580 -7.

   Defines the following functions for returning UCP data:
       - kazarlis(times=1): make standard, kazarlis data [2] (no valve-point effect)
       - eld13(load=1800): load dispatch instance provided by [1] (valve-point effect)
       - eld40(load=10500): load dispatch instance provided by [3] (valve-point effect)
       - ucp10(periods): kazarlis data, complemented with parameters for valve effect
       - ucp5(periods): reduced kazarlis [2] data, complemented with parameters for valve effect
       - ucp13(periods): costs taken form eld13, with multiperiod data from kazarlis
       - ucp40(periods): costs taken form eld40, with multiperiod data from kazarlis
       - toy(periods): make data for toy instance, based on ucp10
       
"""

